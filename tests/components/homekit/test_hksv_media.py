@pytest.mark.parametrize(
    ("field", "value"),
    [
        ("width", 640),
        ("height", 480),
        ("h264_profile_idc", 100),
        ("h264_level_idc", 50),
        ("peak_fps", 16),
        ("peak_video_bitrate", 501_000),
        ("max_keyframe_interval", 1.1),
        ("observation_seconds", 1),
    ],
)
def test_copy_video_rejects_observed_limit_violation(field: str, value: float) -> None:
    """A native copy path requires every observed constraint to fit."""
    observed = MediaObservation(
        "h264", 66, 31, 320, 240, None, None, None, None, 15, 1, 15, 400_000, 300_000, 4
    )
    config = RecordingConfiguration(
        4000, 1, 4000, 0, 0, 500, 1000, 320, 240, 15, 0, 1, 0, 1, 32
    )
    assert can_copy_video(observed, config)
    assert not can_copy_video(replace(observed, **{field: value}), config)


async def test_monitored_copy_stops_before_invalid_fragment(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Recheck every fragment window before releasing copied video."""
    good = MediaObservation(
        "h264", 66, 31, 320, 240, None, None, None, None, 15, 1, 15, 400_000, 300_000, 4
    )
    bad = replace(good, peak_fps=20)
    observations = iter((good, bad))
    monkeypatch.setattr(
        hksv_controller, "inspect_recording", lambda *_: next(observations)
    )
    config = RecordingConfiguration(
        4000, 1, 4000, 0, 2, 500, 1000, 320, 240, 15, 0, 1, 0, 2, 32
    )

    class Shared:
        async def fragments(self) -> AsyncIterator[SharedFragment]:
            yield SharedFragment(1, 1, b"init", b"one", 4)
            yield SharedFragment(1, 2, b"init", b"two", 4)
            yield SharedFragment(1, 3, b"init", b"bad", 4)

    async def source(_with_audio: bool) -> None:
        return None

    controller = hksv_controller.HKSVController(source, "ffmpeg", None)
    assert [f.data async for f in controller._monitored_copy(Shared(), config)] == [
        b"one"
    ]
    assert controller._copy_disabled


async def test_native_probe_adds_supported_resolution(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Advertise observed native dimensions alongside required fallback formats."""
    observed = MediaObservation(
        "h264",
        100,
        32,
        1280,
        960,
        None,
        None,
        None,
        None,
        30,
        1,
        30,
        400_000,
        300_000,
        4,
    )
    monkeypatch.setattr(hksv_controller, "inspect_recording", lambda *_: observed)

    class Shared:
        closed = False

        def snapshot(self) -> tuple[SharedFragment, ...]:
            return (
                SharedFragment(1, 1, b"init", b"one", 4),
                SharedFragment(1, 2, b"init", b"two", 4),
            )

        async def close(self) -> None:
            self.closed = True

    shared = Shared()

    async def source(_with_audio: bool) -> Shared:
        return shared

    controller = hksv_controller.HKSVController(source, "ffmpeg", None)
    await controller._discover_native()
    assert (1280, 960, 30) in controller.capabilities.resolutions
    assert (1920, 1080, 30) in controller.capabilities.resolutions
    assert shared.closed
