async def test_slow_recording_consumer_is_bounded() -> None:
    """Disconnect a consumer before its queued data exceeds its budget."""
    process = RecordingProcess([], 4, 30)
    process.buffer.set_initialization(b"i")
    process._task = asyncio.create_task(asyncio.sleep(60))
    process._ready.set()
    fragments = process.fragments()
    assert await anext(fragments) == b"i"
    process._publish(b"12345678")
    process._publish(b"12345678")
    with pytest.raises(StopAsyncIteration):
        await anext(fragments)
    await process.stop()


@pytest.mark.parametrize("copy_video", [False, True])
async def test_transcode_shared_fragment_input(copy_video: bool) -> None:
    """Remux or transcode shared fragmented MP4 over stdin."""
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        pytest.skip("FFmpeg is not installed")
    producer = await asyncio.create_subprocess_exec(
        ffmpeg,
        "-v",
        "error",
        "-f",
        "lavfi",
        "-i",
        "testsrc=size=320x240:rate=15",
        "-t",
        "3",
        "-c:v",
        "libx264",
        "-g",
        "15",
        "-movflags",
        "frag_keyframe+empty_moov+default_base_moof",
        "-f",
        "mp4",
        "pipe:1",
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.DEVNULL,
    )
    assert producer.stdout is not None

    async def input_data() -> AsyncIterator[bytes]:
        while chunk := await producer.stdout.read(4096):
            yield chunk

    config = RecordingConfiguration(
        4000, 1, 4000, 0, 0, 500, 1000, 320, 240, 15, 0, 1, 0, 1, 32
    )
    process = RecordingProcess(
        ffmpeg_command(ffmpeg, ["-i", "pipe:0"], config, False, copy_video=copy_video),
        4,
        5_000_000,
    )
    await process.start(input_data())
    try:
        packets = [packet async for packet in process.fragments()]
        assert len(packets) >= 2
        assert await producer.wait() == 0
    finally:
        await process.stop()
        if producer.returncode is None:
            producer.kill()
            await producer.wait()


async def test_shared_input_stops_at_discontinuity() -> None:
    """Never feed a second generation into an existing MP4 decoder."""

    async def source() -> AsyncIterator[SharedFragment]:
        yield SharedFragment(1, 1, b"init", b"one", 4)
        yield SharedFragment(1, 2, b"init", b"two", 4)
        yield SharedFragment(2, 3, b"new-init", b"three", 4)

    assert [chunk async for chunk in shared_mp4_input(source())] == [
        b"init",
        b"one",
        b"two",
    ]


