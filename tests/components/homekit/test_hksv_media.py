async def test_monitored_copy_stops_before_invalid_fragment(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Recheck every fragment window before releasing copied video."""
    good = MediaObservation(
        "h264", 66, 31, 320, 240, None, None, None, None, 15, 1, 15, 400_000, 300_000, 4
    )
